-- SQL — язык для работы с данными в реляционных базах.
-- Пример для PostgreSQL. Основы обычно даются легко (1–2/5),
-- JOIN и группировки — средне (3/5), оптимизация — сложнее (4–5/5).

-- Таблицы описывают данные. PRIMARY KEY — уникальный идентификатор,
-- NOT NULL — обязательное поле, REFERENCES — связь между таблицами.
CREATE TABLE students (
	id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	age  INTEGER CHECK (age > 0)
);

CREATE TABLE courses (
	id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title TEXT NOT NULL
);

-- Таблица связей: студент может изучать несколько курсов,
-- а на каждом курсе может быть несколько студентов.
CREATE TABLE enrollments (
	student_id INTEGER REFERENCES students(id),
	course_id  INTEGER REFERENCES courses(id),
	PRIMARY KEY (student_id, course_id)
);

-- INSERT добавляет данные.
INSERT INTO students (name, age) VALUES
	('Аня', 19),
	('Иван', 22),
	('Маша', 20);

INSERT INTO courses (title) VALUES ('SQL'), ('Python');

INSERT INTO enrollments (student_id, course_id) VALUES
	(1, 1),
	(1, 2),
	(2, 1);

-- SELECT читает данные, WHERE отбирает строки, ORDER BY сортирует.
SELECT * FROM students;

SELECT name, age
FROM students
WHERE age >= 20
ORDER BY age DESC;

-- JOIN объединяет связанные таблицы.
SELECT students.name, courses.title AS course
FROM enrollments
JOIN students ON students.id = enrollments.student_id
JOIN courses ON courses.id = enrollments.course_id
ORDER BY students.name;

-- COUNT считает строки, GROUP BY группирует их.
SELECT courses.title, COUNT(enrollments.student_id) AS student_count
FROM courses
LEFT JOIN enrollments ON enrollments.course_id = courses.id
GROUP BY courses.id, courses.title
ORDER BY courses.title;

-- UPDATE изменяет данные. Без WHERE изменятся все строки!
UPDATE students
SET age = 20
WHERE name = 'Аня';

-- DELETE удаляет данные. Без WHERE удалятся все строки!
-- DELETE FROM students WHERE id = 3;

-- Транзакция: ROLLBACK отменит сделанное внутри неё изменение.
BEGIN;
UPDATE students SET age = age + 1 WHERE id = 1;
ROLLBACK;

-- Кратко: SELECT — посмотреть, INSERT — добавить,
-- UPDATE — изменить, DELETE — удалить.
